#!/usr/bin/env python3
"""store-export.py: write the store's REFERENCE DATA back into db/ as migrations.

    python tools/store-export.py            what would change
    python tools/store-export.py --apply    rewrite the seed migrations
    python tools/store-export.py --self-test

WHY THIS EXISTS (2026-09-16): "backfill entries and questions and answers
and test each so that we have a shape and an efficient location for all your
brains."

TWO KINDS OF ROW LIVE IN THIS STORE AND ONLY ONE OF THEM IS STATE.

  STATE, and it belongs only in the store: runs, lanes, jobs, events. It is
  written by whichever machine did the thing, it is different every hour, and
  the repo must never hold a copy (`rules/shared/memory-integrity.md`: a local
  store may never answer a question about another machine).

  REFERENCE DATA, which behaves like schema: `queries` (the stored questions,
  golden rule A6) and `commands` (the allowed command forms an order's Commands
  section is built from). Two machines cannot disagree about it, it changes
  deliberately, and **a repo that cannot rebuild it is one pruned volume from
  losing it.**

Measured the day this was written: 13 stored questions and 40 command forms were
live, and `db/` could rebuild NEITHER. `db/002_stored_queries.sql` was a
`pg_dump` data dump masquerading as a migration: psql-only `\\restrict`
meta-commands, plain INSERTs with no ON CONFLICT so it could not be re-applied at
all, seven of the thirteen questions missing, and one question (`launchable`)
that had been superseded by `marked_pending` months earlier and would have been
restored as current.

SO THE FILE IS GENERATED, NEVER HAND-EDITED. A hand-maintained list of rows
drifts from the rows; that is the whole reason these moved into a table. Editing
the output is the defect, and re-running this is the fix.
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent

# WHAT IS EXPORTED, DECLARED (`docs/scoped-by-declaration.md`). A tool that
# worked out at runtime which tables "look like reference data" would eventually
# dump `runs` into git.
#   table -> (schema_version, output file, key columns, all columns, why)
#
# THE SEED NUMBERS ARE DELIBERATELY THE HIGHEST IN `db/`, and that is a
# correctness requirement rather than tidiness. Migrations apply in numeric
# order, so a generated seed must land AFTER every DDL migration that also
# introduces rows. The first draft of this put the stored questions at 002 while
# `007_sky_knowledge.sql` seeded three of its own, which meant the file
# regenerated from the live store applied FIRST and the hand-written copy in 007
# overwrote it with whatever it said months ago. Renumber upward when a new DDL
# migration passes these.
EXPORTS: dict[str, tuple[int, str, tuple[str, ...], tuple[str, ...], str]] = {
    "queries": (
        9, "db/009_stored_queries.sql", ("name",),
        ("name", "question", "sql_text", "returns", "args"),
        "every stored question, so a recurring answer is never re-derived "
        "(golden rule A6)",
    ),
    "commands": (
        10, "db/010_command_forms.sql", ("id",),
        ("id", "purpose", "machine", "repo", "form", "tool", "verified_on",
         "note"),
        "every allowed command form, which an order's Commands section is "
        "built from rather than copied out of a hand-written table",
    ),
}

HEADER = """\
-- {out}
--
-- GENERATED BY `tools/store-export.py`. Do not hand-edit: the rows live in the
-- store and this file is a rebuildable copy of them, so an edit here is
-- overwritten the next time it runs. To change a row, change it in the store.
--
-- {why}
--
-- Idempotent on purpose: every row is an upsert on {keys}, so applying this to
-- a live store is a no-op and applying it to an empty one restores the lot.
"""


def _memdb():
    spec = importlib.util.spec_from_file_location("memdb", HERE / "memdb.py")
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def sql_literal(value) -> str:
    """A Postgres literal. NULL and the empty string are DIFFERENT here.

    `verified_on IS NULL` means UNVERIFIED and an empty string would be a date
    parse error, so collapsing them is not a cosmetic choice.
    """
    if value is None:
        return "NULL"
    text = str(value)
    return "'" + text.replace("'", "''") + "'"


def render(table: str, rows: list[list]) -> str:
    """The whole migration file for one table. Pure, so it is tested dry."""
    version, out, keys, cols, why = EXPORTS[table]
    body = [HEADER.format(out=out, why=why, keys=", ".join(keys))]
    if rows:
        body.append(f"\nINSERT INTO {table} ({', '.join(cols)}) VALUES")
        tuples = []
        for row in rows:
            tuples.append("    (" + ", ".join(sql_literal(v) for v in row) + ")")
        body.append(",\n".join(tuples))
        updates = [c for c in cols if c not in keys]
        body.append(f"ON CONFLICT ({', '.join(keys)}) DO UPDATE SET")
        body.append(",\n".join(f"    {c} = EXCLUDED.{c}" for c in updates) + ";")
    else:
        # AN EMPTY TABLE IS WRITTEN DOWN AS EMPTY, never as an absent file: a
        # missing file reads as "nobody exported this yet", which is a
        # different and much more forgivable state than "there is nothing".
        body.append(f"\n-- {table} held NO rows when this was generated.")
    body.append(f"\nINSERT INTO schema_version (version, note) VALUES\n"
                f"    ({version}, {sql_literal(why)})\n"
                f"ON CONFLICT (version) DO NOTHING;")
    return "\n".join(body) + "\n"


def run(apply: bool) -> int:
    memdb = _memdb()
    changed = 0
    for table, (_version, out, keys, cols, _why) in sorted(EXPORTS.items()):
        order = ", ".join(keys)
        try:
            rows = memdb._query(
                f"select {', '.join(cols)} from {table} order by {order}", ())
        except Exception as exc:
            print(f"store-export: could NOT ask the store ({exc}). Nothing "
                  f"was written.", file=sys.stderr)
            return 3
        target = REPO / out
        text = render(table, rows)
        was = target.read_text(encoding="utf-8") if target.exists() else ""
        if was == text:
            print(f"  {out}: unchanged, {len(rows)} row(s)")
            continue
        changed += 1
        if not apply:
            print(f"  {out}: WOULD REWRITE, {len(rows)} row(s) in the store")
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        print(f"  {out}: rewritten, {len(rows)} row(s)")
    # ONE LINE, and not an f-string holding a split literal. A replacement
    # field spanning two lines is legal only from Python 3.12 (PEP 701), so the
    # earlier spelling was a SyntaxError on 3.11: this whole file failed to
    # parse on the Mac and in a cloud container, which took the portability
    # check and the entire lint down with it (measured 2026-09-22).
    tail = "rewritten" if apply else "pending; re-run with --apply"
    print(f"\n{changed} file(s) {tail}")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="store-export")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args(argv)
    if a.self_test:
        return self_test()
    return run(a.apply)


def self_test() -> int:
    fails, checks = [], 0

    def want(label, cond):
        nonlocal checks
        checks += 1
        print("  %s  %s" % ("ok  " if cond else "FAIL", label))
        if not cond:
            fails.append(label)

    want("a quote in a value is doubled, not escaped with a backslash",
         sql_literal("it''s") == "'it''''s'")
    # NULL AND '' ARE DIFFERENT. Red-proven by returning '' for None: the
    # commands export then writes '' into a date column and the migration dies
    # on apply, which is the failure mode that looks like a bad table.
    want("None becomes NULL, never an empty string", sql_literal(None) == "NULL")
    want("an empty string stays an empty string", sql_literal("") == "''")

    out = render("queries", [["cards", "How many?", "SELECT 1", "a count", None]])
    want("the insert names every declared column",
         "INSERT INTO queries (name, question, sql_text, returns, args) VALUES"
         in out)
    # IDEMPOTENT OR IT IS NOT A MIGRATION. This is the exact fault in the
    # pg_dump file it replaces: plain INSERTs that cannot be re-applied.
    want("it upserts on the key, so re-applying is a no-op",
         "ON CONFLICT (name) DO UPDATE SET" in out)
    want("and the key itself is never in the SET list, which is a no-op update",
         "name = EXCLUDED.name" not in out)
    want("a NULL argument list is written as NULL", "NULL)" in out)
    want("the schema_version row is recorded, so the migration counts as applied",
         "INSERT INTO schema_version (version, note) VALUES" in out
         and f"({EXPORTS['queries'][0]}, " in out)
    want("the file says it is generated, so nobody hand-edits it",
         "GENERATED BY" in out and "Do not hand-edit" in out)

    empty = render("commands", [])
    want("an empty table is written down as empty rather than left absent",
         "held NO rows" in empty and "INSERT INTO commands" not in empty)
    want("and it still records its version",
         "INSERT INTO schema_version" in empty
         and f"({EXPORTS['commands'][0]}, " in empty)

    two = render("commands", [
        ["git-any", "any git verb", "any", None, "git -C {repo} {verb}", "bash",
         "2026-08-21", None],
        ["python-system", "a memory-bank tool", "pc", None, "py {script}",
         "bash", None, "per script"],
    ])
    want("several rows become ONE insert with comma-separated tuples",
         two.count("ON CONFLICT (id) DO UPDATE") == 1
         and two.count("\n    ('") == 2)
    want("an unverified command keeps its NULL date rather than a blank",
         "'python-system'" in two and "NULL, 'per script'" in two)

    if fails:
        print(f"\nstore-export self-test: {len(fails)} of {checks} FAILED")
        return 1
    print(f"\nstore-export self-test: {checks} assertions passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
